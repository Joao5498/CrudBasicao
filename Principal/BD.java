package Principal;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import javax.swing.JOptionPane;

public class BD {
    private static final String URL = "jdbc:oracle:thin:@//localhost:1521/FREEPDB1";
    private static final String USUARIO = "CRUD_BASICAO";
    private static final String SENHA = "Teste@123";
    
    public static boolean criaTabela(){
        Connection conexao = conectar();
        try{
            String v_exist_t = "SELECT COUNT(*) FROM USER_TABLES WHERE TABLE_NAME = 'PRODUTOS'";
            PreparedStatement ps = conexao.prepareStatement(v_exist_t);            
            ResultSet rs = ps.executeQuery();
            rs.next();
            
            int quantidade = rs.getInt(1);
            
            if(quantidade > 0){
                JOptionPane.showMessageDialog(null, "A tabela já foi criada.");
            }else{
                String cria_tabela = "CREATE TABLE PRODUTOS(\n"
                        + "	ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,\n"
                        + "	DESCRICAO VARCHAR2(50),\n"
                        + "	PRECO NUMBER(10,4),\n"
                        + "	QUANTIDADE INTEGER\n"
                        + ")";
                ps = conexao.prepareStatement(cria_tabela);
                ps.execute();
                
                System.out.println("Tabela criada com sucesso!");
                return true;                        
            }
        }catch(SQLException e){
            JOptionPane.showMessageDialog(null, e.getErrorCode() + e.getMessage());
        }finally{
            desconectar(conexao);
        }
        return false;
    }
    
    public static Connection conectar(){
        try{
            Connection conexao = DriverManager.getConnection(URL, USUARIO, SENHA);
            System.out.println("Conectou");
            return conexao;            
        }catch(SQLException e){
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
        return null;
    }
    
    public static void desconectar(Connection conexao){
        try{
            if(conexao != null && !conexao.isClosed()){
                System.out.println("Desconectou");
                conexao.close();            
            }

        }catch(SQLException e){
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
        
    }
}